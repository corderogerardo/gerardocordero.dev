const { withDangerousMod } = require("@expo/config-plugins");
const fs = require("node:fs");
const path = require("node:path");

/**
 * Aligns every CocoaPods target's `IPHONEOS_DEPLOYMENT_TARGET` with the app's own.
 *
 * Why this exists: Xcode 27 rejects any pod whose deployment target is below iOS
 * 15.0 with a hard build error (`The iOS Simulator deployment target ... is set to
 * 12.0, but the range of supported deployment target versions is 15.0 to 27.2.x`).
 * `ReachabilitySwift`, pulled in by `expo-updates`, still declares 12.0. The pod is
 * compiled into the app and links against the app's SDK anyway, so aligning its
 * deployment target with the app's is the supported fix — the alternative is pinning
 * the whole toolchain to an older Xcode.
 *
 * Why a config plugin and not a hand-edited `ios/Podfile`: `ios/` is generated and
 * gitignored (continuous native generation). An edit there survives exactly until the
 * next `expo prebuild --clean`. A plugin is the reproducible version of the same edit.
 *
 * Fails loudly if the generated Podfile stops looking like the template this was
 * written against: a silent no-op here produces a build error ten minutes later.
 */
const MARKER = "# @generated by plugins/withIosDeploymentTarget.js";

const SNIPPET = `${MARKER} — do not edit ios/Podfile by hand.
    # See the plugin for the full rationale. Summary: Xcode 27 refuses pods whose
    # deployment target is below iOS 15.0, and some podspecs still declare 11.0/12.0.
    pods_deployment_target = podfile_properties['ios.deploymentTarget'] || '16.4'
    installer.pods_project.targets.each do |pod_target|
      pod_target.build_configurations.each do |pod_config|
        pod_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = pods_deployment_target
      end
    end
`;

function injectPodfile(podfile) {
  if (podfile.includes(MARKER)) return podfile;

  // The generated Podfile ends with:
  //     )
  //   end        <- closes post_install
  // end          <- closes the target block
  // Insert before that closing `end` so the override runs *after*
  // react_native_post_install, which also touches pod build settings.
  const closing = "\n  end\nend";
  const at = podfile.lastIndexOf(closing);
  if (at !== -1) {
    return `${podfile.slice(0, at)}\n\n${SNIPPET}${podfile.slice(at)}`;
  }

  // Fallback: run before the rest of post_install. Documented, not silent.
  const anchor = "  post_install do |installer|\n";
  const anchorAt = podfile.indexOf(anchor);
  if (anchorAt === -1) {
    throw new Error(
      "withIosDeploymentTarget: could not find a post_install block in the generated Podfile. " +
        "The Expo Podfile template changed; update plugins/withIosDeploymentTarget.js.",
    );
  }
  console.warn(
    "withIosDeploymentTarget: post_install closing `end` not found; injecting at the top of the block. " +
      "Verify that IPHONEOS_DEPLOYMENT_TARGET survives the build.",
  );
  return (
    podfile.slice(0, anchorAt + anchor.length) + SNIPPET + podfile.slice(anchorAt + anchor.length)
  );
}

module.exports = function withIosDeploymentTarget(config) {
  return withDangerousMod(config, [
    "ios",
    async (cfg) => {
      const podfilePath = path.join(cfg.modRequest.platformProjectRoot, "Podfile");
      const podfile = await fs.promises.readFile(podfilePath, "utf8");
      await fs.promises.writeFile(podfilePath, injectPodfile(podfile), "utf8");
      return cfg;
    },
  ]);
};
